using Microsoft.OpenApi;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Net.Http;

namespace PilotApi.Integration.Tests.Testing.Utilities
{
	/// <summary>
	/// Compares two <see cref="OpenApiDocument"/> instances and reports differences.
	/// </summary>
	public static class OpenApiComparisonUtilities
	{
		/// <summary>
		/// Compares an expected (reference) OpenAPI document against an actual (application-generated) one.
		/// </summary>
		/// <param name="expected">
		/// The reference OpenAPI document (for example, the shared YAML specification).
		/// </param>
		/// <param name="actual">
		/// The OpenAPI document generated by the running application.
		/// </param>
		/// <returns>
		/// An <see cref="OpenApiComparisonResult"/> containing any errors and warnings found.
		/// </returns>
		public static OpenApiComparisonResult Compare(OpenApiDocument expected, OpenApiDocument actual)
		{
			if (expected == null)
			{
				throw new ArgumentException($"Invalid argument : {nameof(expected)}. "
					+ $"A valid object type of: '{typeof(OpenApiDocument)}' is needed to continue. ({nameof(OpenApiComparisonUtilities)})");
			}

			if (actual == null)
			{
				throw new ArgumentException($"Invalid argument : {nameof(actual)}. "
					+ $"A valid object type of: '{typeof(OpenApiDocument)}' is needed to continue. ({nameof(OpenApiComparisonUtilities)})");
			}

			var result = new OpenApiComparisonResult();

			CompareInfo(expected, actual, result);
			ComparePaths(expected, actual, result);
			CompareComponentSchemas(expected, actual, result);

			return result;
		}

		/// <summary>
		/// Compares the Info section of the expected and actual OpenAPI documents and records any differences in the result.
		/// </summary>
		/// <param name="expected">The expected OpenAPI document.</param>
		/// <param name="actual">The actual OpenAPI document.</param>
		/// <param name="result">The comparison result to record any differences.</param>
		private static void CompareInfo(OpenApiDocument expected, OpenApiDocument actual, OpenApiComparisonResult result)
		{
			var expectedInfo = expected.Info;
			var actualInfo = actual.Info;

			if (expectedInfo == null || actualInfo == null)
			{
				result.Errors.Add("The Info section is missing from the expected or actual document.");
				return;
			}

			CompareValue(nameof(expectedInfo.Title), expectedInfo.Title, actualInfo.Title, result.Errors);
			CompareValue(nameof(expectedInfo.Description), expectedInfo.Description, actualInfo.Description, result.Errors);
			CompareValue(nameof(expectedInfo.Summary), expectedInfo.Summary, actualInfo.Summary, result.Errors);

			var expectedContactEmail = expectedInfo.Contact?.Email;
			var actualContactEmail = actualInfo.Contact?.Email;
			CompareValue("Info.Contact.Email", expectedContactEmail, actualContactEmail, result.Errors);

			var expectedContactName = expectedInfo.Contact?.Name;
			var actualContactName = actualInfo.Contact?.Name;
			CompareValue("Info.Contact.Name", expectedContactName, actualContactName, result.Errors);
			CompareValue("Info.Contact.Url", expectedInfo.Contact?.Url?.ToString(), actualInfo.Contact?.Url?.ToString(), result.Errors);

			var expectedLicenseName = expectedInfo.License?.Name;
			var actualLicenseName = actualInfo.License?.Name;
			CompareValue("Info.License.Name", expectedLicenseName, actualLicenseName, result.Errors);
		}

		/// <summary>
		/// Compares the path definitions in two OpenAPI documents and records missing paths in the comparison result.	
		/// </summary>
		/// <remarks>Treats a null Paths collection as empty in either document and checks for paths missing from
		/// either side.</remarks>
		/// <param name="expected">The OpenAPI document that defines the expected path set.</param>
		/// <param name="actual">The OpenAPI document that defines the implemented path set.</param>
		/// <param name="result">The comparison result that collects path mismatch errors.</param>
		private static void ComparePaths(OpenApiDocument expected, OpenApiDocument actual, OpenApiComparisonResult result)
		{
			var expectedPaths = expected.Paths ?? new OpenApiPaths();
			var actualPaths = actual.Paths ?? new OpenApiPaths();

			foreach (var expectedPathKey in expectedPaths.Keys)
			{
				if (!actualPaths.TryGetValue(expectedPathKey, out var actualPathItem))
				{
					result.Errors.Add($"Path '{expectedPathKey}' is defined in the expected specification but is missing from the application.");
					continue;
				}

				var expectedPathItem = expectedPaths[expectedPathKey];
				CompareOperations(expectedPathKey, expectedPathItem, actualPathItem, result);
			}

			foreach (var actualPathKey in actualPaths.Keys)
			{
				if (!expectedPaths.ContainsKey(actualPathKey))
				{
					result.Errors.Add($"Path '{actualPathKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares the expected and actual OpenAPI operations for a path and records mismatches, including missing
		/// operations and differences in parameters, responses, and security requirements.	
		/// </summary>
		/// <remarks>Treats missing operation collections as empty and validates operations in both
		/// directions.</remarks>
		/// <param name="pathKey">Path identifier used in operation comparison messages.</param>
		/// <param name="expectedPathItem">Path item from the expected OpenAPI specification.</param>
		/// <param name="actualPathItem">Path item produced by the application.</param>
		/// <param name="result">Comparison result collector that receives validation errors.</param>
		private static void CompareOperations(
			string pathKey,
			IOpenApiPathItem expectedPathItem,
			IOpenApiPathItem actualPathItem,
			OpenApiComparisonResult result)
		{
			var expectedOperations = expectedPathItem.Operations ?? new Dictionary<HttpMethod, OpenApiOperation>();
			var actualOperations = actualPathItem.Operations ?? new Dictionary<HttpMethod, OpenApiOperation>();

			foreach (var expectedOperationPair in expectedOperations)
			{
				var method = expectedOperationPair.Key;
				if (!actualOperations.TryGetValue(method, out var actualOperation))
				{
					result.Errors.Add($"Operation '{method} {pathKey}' is defined in the expected specification but is missing from the application.");
					continue;
				}

				CompareParameters(pathKey, method, expectedOperationPair.Value, actualOperation, result);
				CompareResponses(pathKey, method, expectedOperationPair.Value, actualOperation, result);
				CompareSecurity(pathKey, method, expectedOperationPair.Value, actualOperation, result);
			}

			foreach (var actualOperationPair in actualOperations)
			{
				if (!expectedOperations.ContainsKey(actualOperationPair.Key))
				{
					result.Errors.Add($"Operation '{actualOperationPair.Key} {pathKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares expected and actual OpenAPI operation parameters by name and required flag, and records any mismatches.
		/// </summary>
		/// <remarks>Checks for parameters missing from the application, parameters missing from the expected
		/// specification, and differences in the Required setting for parameters with matching names.</remarks>
		/// <param name="pathKey">Operation path used in mismatch messages.</param>
		/// <param name="method">HTTP method used in mismatch messages.</param>
		/// <param name="expectedOperation">Operation definition from the expected specification.</param>
		/// <param name="actualOperation">Operation definition from the application.</param>
		/// <param name="result">Comparison result that collects parameter mismatch errors.</param>
		private static void CompareParameters(
			string pathKey,
			HttpMethod method,
			OpenApiOperation expectedOperation,
			OpenApiOperation actualOperation,
			OpenApiComparisonResult result)
		{
			var expectedParameters = expectedOperation.Parameters ?? new List<IOpenApiParameter>();
			var actualParameters = actualOperation.Parameters ?? new List<IOpenApiParameter>();

			var expectedNames = expectedParameters.Select(p => p.Name).ToList();
			var actualNames = actualParameters.Select(p => p.Name).ToList();

			foreach (var expectedName in expectedNames)
			{
				if (!actualNames.Contains(expectedName))
				{
					result.Errors.Add($"Parameter '{expectedName}' on operation '{method} {pathKey}' is defined in the expected specification but is missing from the application.");
					continue;
				}

				var expectedParameter = expectedParameters.First(p => p.Name == expectedName);
				var actualParameter = actualParameters.First(p => p.Name == expectedName);

				if (expectedParameter.Required != actualParameter.Required)
				{
					result.Errors.Add(
						$"Parameter '{expectedName}' on operation '{method} {pathKey}' has Required={expectedParameter.Required} in the expected " +
						$"specification but Required={actualParameter.Required} in the application.");
				}
			}

			foreach (var actualName in actualNames)
			{
				if (!expectedNames.Contains(actualName))
				{
					result.Errors.Add($"Parameter '{actualName}' on operation '{method} {pathKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares the response status codes in expected and actual OpenAPI operations and records any missing codes as
		/// errors.
		/// </summary>
		/// <remarks>Treats missing response collections as empty and validates only the presence of response status
		/// code entries.</remarks>
		/// <param name="pathKey">Path template identifying the API endpoint being compared.</param>
		/// <param name="method">HTTP method of the operation being compared.</param>
		/// <param name="expectedOperation">Expected OpenAPI operation definition.</param>
		/// <param name="actualOperation">Actual OpenAPI operation definition from the application.</param>
		/// <param name="result">Comparison result that collects validation errors.</param>
		private static void CompareResponses(
			string pathKey,
			HttpMethod method,
			OpenApiOperation expectedOperation,
			OpenApiOperation actualOperation,
			OpenApiComparisonResult result)
		{
			var expectedResponses = expectedOperation.Responses ?? new OpenApiResponses();
			var actualResponses = actualOperation.Responses ?? new OpenApiResponses();

			foreach (var expectedStatusCode in expectedResponses.Keys)
			{
				if (!actualResponses.ContainsKey(expectedStatusCode))
				{
					result.Errors.Add($"Response status code '{expectedStatusCode}' on operation '{method} {pathKey}' is defined in the expected specification but is missing from the application.");
				}
			}

			foreach (var actualStatusCode in actualResponses.Keys)
			{
				if (!expectedResponses.ContainsKey(actualStatusCode))
				{
					result.Errors.Add($"Response status code '{actualStatusCode}' on operation '{method} {pathKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares whether the expected and actual OpenAPI operations both define security requirements and records a
		/// mismatch.
		/// </summary>
		/// <remarks>Only the presence of security requirements is compared, not the specific requirement
		/// contents.</remarks>
		/// <param name="pathKey">Path template of the operation being compared.</param>
		/// <param name="method">HTTP method of the operation being compared.</param>
		/// <param name="expectedOperation">Expected OpenAPI operation definition.</param>
		/// <param name="actualOperation">Actual OpenAPI operation definition.</param>
		/// <param name="result">Comparison result that collects validation errors.</param>
		private static void CompareSecurity(
			string pathKey,
			HttpMethod method,
			OpenApiOperation expectedOperation,
			OpenApiOperation actualOperation,
			OpenApiComparisonResult result)
		{
			var expectedRequiresSecurity = (expectedOperation.Security?.Count ?? 0) > 0;
			var actualRequiresSecurity = (actualOperation.Security?.Count ?? 0) > 0;

			if (expectedRequiresSecurity != actualRequiresSecurity)
			{
				result.Errors.Add(
					$"Operation '{method} {pathKey}' has a security requirement mismatch. Expected security present: {expectedRequiresSecurity}, " +
					$"actual security present: {actualRequiresSecurity}.");
			}
		}

		/// <summary>
		/// Compares component schemas between the expected and actual OpenAPI documents, records warnings for schemas missing
		/// on either side, and compares properties for schemas present in both.
		/// </summary>
		/// <remarks>Treats missing component schema collections as empty and performs a two-way presence
		/// check.</remarks>
		/// <param name="expected">OpenAPI document that defines the expected component schemas.</param>
		/// <param name="actual">OpenAPI document that provides the implemented component schemas.</param>
		/// <param name="result">Comparison result container that receives schema-related warnings.</param>
		private static void CompareComponentSchemas(OpenApiDocument expected, OpenApiDocument actual, OpenApiComparisonResult result)
		{
			var expectedSchemas = expected.Components?.Schemas ?? new Dictionary<string, IOpenApiSchema>();
			var actualSchemas = actual.Components?.Schemas ?? new Dictionary<string, IOpenApiSchema>();

			foreach (var expectedSchemaKey in expectedSchemas.Keys)
			{
				if (!actualSchemas.ContainsKey(expectedSchemaKey))
				{
					result.Warnings.Add($"Schema '{expectedSchemaKey}' is defined in the expected specification but is missing from the application.");
					continue;
				}

				CompareSchemaProperties(expectedSchemaKey, expectedSchemas[expectedSchemaKey], actualSchemas[expectedSchemaKey], result);
			}

			foreach (var actualSchemaKey in actualSchemas.Keys)
			{
				if (!expectedSchemas.ContainsKey(actualSchemaKey))
				{
					result.Warnings.Add($"Schema '{actualSchemaKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares the property keys defined on the expected and actual schemas and records warnings for missing properties
		/// on either side.
		/// </summary>
		/// <remarks>Only property presence is checked; property types, formats, and nested schema details are not
		/// compared.</remarks>
		/// <param name="schemaKey">Schema identifier used in warning messages.</param>
		/// <param name="expectedSchema">Schema from the expected specification.</param>
		/// <param name="actualSchema">Schema implemented by the application.</param>
		/// <param name="result">Comparison result that collects warning messages.</param>
		private static void CompareSchemaProperties(
			string schemaKey,
			IOpenApiSchema expectedSchema,
			IOpenApiSchema actualSchema,
			OpenApiComparisonResult result)
		{
			var expectedProperties = expectedSchema.Properties ?? new Dictionary<string, IOpenApiSchema>();
			var actualProperties = actualSchema.Properties ?? new Dictionary<string, IOpenApiSchema>();

			foreach (var expectedPropertyKey in expectedProperties.Keys)
			{
				if (!actualProperties.ContainsKey(expectedPropertyKey))
				{
					result.Warnings.Add($"Property '{expectedPropertyKey}' on schema '{schemaKey}' is defined in the expected specification but is missing from the application.");
				}
			}

			foreach (var actualPropertyKey in actualProperties.Keys)
			{
				if (!expectedProperties.ContainsKey(actualPropertyKey))
				{
					result.Warnings.Add($"Property '{actualPropertyKey}' on schema '{schemaKey}' is implemented by the application but is missing from the expected specification.");
				}
			}
		}

		/// <summary>
		/// Compares two string values using ordinal comparison and adds a mismatch message to the error collection when they
		/// differ.
		/// </summary>
		/// <param name="fieldName">Name of the field being compared.</param>
		/// <param name="expectedValue">Expected field value.</param>
		/// <param name="actualValue">Actual field value.</param>
		/// <param name="errors">Collection that receives the mismatch message.</param>
		private static void CompareValue(string fieldName, string expectedValue, string actualValue, ICollection<string> errors)
		{
			if (!string.Equals(expectedValue, actualValue, StringComparison.Ordinal))
			{
				errors.Add($"{fieldName} mismatch. Expected: '{expectedValue}', Actual: '{actualValue}'.");
			}
		}
	}
}
